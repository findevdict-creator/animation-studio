ACCESSORY_CATALOG: dict[str, AccessoryDef] = {a.ref: a for a in ACCESSORIES}
ACCESSORY_BY_KEY: dict[str, AccessoryDef] = {a.key: a for a in ACCESSORIES}


def get_accessory_def(ref: str) -> AccessoryDef:
    """``ACCD-GLASSES@0.1``, or a catalog key such as ``glasses``."""
    if ref in ACCESSORY_CATALOG:
        return ACCESSORY_CATALOG[ref]
    if ref in ACCESSORY_BY_KEY:
        return ACCESSORY_BY_KEY[ref]
    raise KeyError(f"no accessory {ref!r} in catalog {CATALOG_VERSION}")


# ------------------------------------------------------------------ conventions
class AccessoryThresholds(_Frozen):
    """What the attach check accepts: in every pose of the suite, at most ``max_inside_share``
    of an item's points may be inside the body, and none deeper than ``max_inside_depth_m``."""

    max_inside_share: float = Field(ge=0, le=1)
    max_inside_depth_m: float = Field(ge=0)
    #: gap kept between an item and what is under it when it is put on
    clearance_m: float = Field(gt=0)


class AccessoryConventions(_Frozen):
    style_profile: str
    finishes: dict[str, Fabric]
    thresholds: AccessoryThresholds
    poses: tuple[str, ...]


FAMILY_CARTOON_ACCESSORIES = AccessoryConventions(
    style_profile="family_cartoon@1.0",
    finishes={
        **{k: FAMILY_CARTOON_CLOTHING.fabrics[k] for k in ("knit", "wool", "leather", "canvas", "nylon")},
        "plastic": Fabric(roughness=0.35, specular=0.5, thickness=0.003),
        "metal": Fabric(roughness=0.25, specular=0.8, thickness=0.002),
        "plush": Fabric(roughness=1.0, specular=0.05, sheen=0.6, thickness=0.004),
    },
    thresholds=AccessoryThresholds(max_inside_share=0.02, max_inside_depth_m=0.006, clearance_m=0.003),
    poses=FAMILY_CARTOON_CLOTHING.poses,
)
ACCESSORY_CONVENTIONS = {FAMILY_CARTOON_ACCESSORIES.style_profile: FAMILY_CARTOON_ACCESSORIES}


def get_accessory_conventions(style_ref: str) -> AccessoryConventions:
    profile = get_style_profile(style_ref)
    try:
        return ACCESSORY_CONVENTIONS[profile.ref]
    except KeyError:
        raise KeyError(f"style profile {profile.ref} has no accessory conventions") from None


# ------------------------------------------------------------------ specification
class AccessoryMaterial(Model):
    finish: str | None = None
    color: str | None = None  # preset name or #RRGGBB
    accent_color: str | None = None


class AccessorySpecification(Model):
    schema_version: Literal["accessory_spec/1"] = SCHEMA_VERSION
    name: str = Field(min_length=1, max_length=80)
    description: str = Field(default="", max_length=2000)
    style_profile: Ref = Field(default_factory=lambda: Ref(id="family_cartoon", version="1.0"))
    rig_profile: Ref | None = None
    item: Ref
    #: default attachment point; a scene may choose another of the item's points
    attach_point: str | None = None
    params: dict[str, float] = Field(default_factory=dict)
    material: AccessoryMaterial = Field(default_factory=AccessoryMaterial)
    #: body-fit profiles the item is declared for; empty means every profile of the style.
    #: The first is the reference body it is built and checked on (default ``child_average``)
    fit_profiles: list[str] = Field(default_factory=list, max_length=16)
    seed: int = Field(default=0, ge=0, lt=2**31)


class ResolvedAccessory(_Frozen):
    name: str
    style_profile: str
    rig_profile: str
    catalog: str
    item: str  # ACCD-X@0.1
    key: str
    category: str
    placement: str
    attach_point: str
    attach_bone: str
    attach_points: tuple[str, ...]
    params: dict[str, float]
    finish: str
    color: str
    accent_color: str | None
    roughness: float
    specular: float
    sheen: float
    #: declared profiles (empty: all of the style) and the one the item is built on
    fit_profiles: tuple[str, ...]
    reference_fit_profile: str
    conflicts_with_slots: tuple[str, ...]
    clearance: float
    seed: int

    def digest(self) -> str:
        return hashlib.sha256(json.dumps(self.model_dump(), sort_keys=True).encode()).hexdigest()

    @property
    def object_name(self) -> str:
        return f"ACC_{self.key}"

    def fits_profile(self, fit_profile: str) -> bool:
        return not self.fit_profiles or fit_profile in self.fit_profiles


class InvalidAccessory(ValueError):
    def __init__(self, issues: list[Issue]):
        self.issues = issues
        super().__init__("; ".join(f"{i.path}: {i.message}" for i in issues if i.severity == "error"))


DEFAULT_REFERENCE_PROFILE = "child_average"


def _color(value: str, presets: dict[str, str], path: str, issues: list[Issue]) -> str | None:
    if value in presets:
        return presets[value]
    if re.fullmatch(HEX, value):
        return value.upper()
    issues.append(Issue(path=path, code="unknown_color",
                        message=f"{value!r} is neither #RRGGBB nor one of {sorted(presets)}"))
    return None


def validate_accessory(spec: AccessorySpecification) -> list[Issue]:
    issues: list[Issue] = []
    try:
        profile = get_style_profile(spec.style_profile.ref)
        conv = get_accessory_conventions(profile.ref)
        colors = get_conventions(profile.ref).colors
    except KeyError as exc:
        return [Issue(path="style_profile", code="unknown_style_profile", message=str(exc.args[0]))]
    rig_ref = spec.rig_profile.ref if spec.rig_profile else profile.rig_profile
    rig = BUILTIN_RIG_PROFILES.get(rig_ref)
    if rig is None:
        issues.append(Issue(path="rig_profile", code="unknown_rig_profile", message=f"no rig profile {rig_ref!r}"))
    try:
        item = get_accessory_def(spec.item.ref)
    except KeyError as exc:
        return [*issues, Issue(path="item", code="unknown_item", message=str(exc.args[0]))]

    if spec.attach_point is not None and spec.attach_point not in item.attach_points:
        issues.append(Issue(path="attach_point", code="not_for_item",
                            message=f"a {item.label} goes on {list(item.attach_points)}"))
    if rig is not None:
        for point in item.attach_points:
            if point not in rig.attachment_points:
                issues.append(Issue(path="item", code="no_attachment_point",
                                    message=f"rig profile {rig.ref} has no attachment point {point!r}"))
    for name, value in spec.params.items():
        d = item.params.get(name)
        if d is None:
            issues.append(Issue(path=f"params.{name}", code="unknown_param",
                                message=f"a {item.label} has parameters {sorted(item.params)}"))
        elif not d.min <= value <= d.max:
            issues.append(Issue(path=f"params.{name}", code="out_of_range",
                                message=f"{value} is outside {d.min}..{d.max}"))
    m = spec.material
    if m.finish is not None:
        if m.finish not in conv.finishes:
            issues.append(Issue(path="material.finish", code="not_in_vocabulary",
                                message=f"{m.finish!r} is not one of {sorted(conv.finishes)}"))
        elif m.finish not in item.finishes:
            issues.append(Issue(path="material.finish", code="not_for_item",
                                message=f"a {item.label} is made of {list(item.finishes)}"))
    if m.color is not None:
        _color(m.color, colors, "material.color", issues)
    if m.accent_color is not None:
        if item.accent is None:
            issues.append(Issue(path="material.accent_color", code="not_supported", severity="warning",
                                message=f"a {item.label} has no second colour; it is ignored"))
        else:
            _color(m.accent_color, colors, "material.accent_color", issues)
    known = fit_profiles(profile)
    for i, fp in enumerate(spec.fit_profiles):
        if fp not in known:
            issues.append(Issue(path=f"fit_profiles[{i}]", code="unknown_fit_profile",
                                message=f"{fp!r} is not one of {known}"))
    if len(set(spec.fit_profiles)) != len(spec.fit_profiles):
        issues.append(Issue(path="fit_profiles", code="duplicate", message="a fit profile is listed twice"))
    return issues


def resolve_accessory(spec: AccessorySpecification) -> ResolvedAccessory:
    issues = validate_accessory(spec)
    if any(i.severity == "error" for i in issues):
        raise InvalidAccessory(issues)
    profile = get_style_profile(spec.style_profile.ref)
    conv = get_accessory_conventions(profile.ref)
    colors = get_conventions(profile.ref).colors
    rig = BUILTIN_RIG_PROFILES[spec.rig_profile.ref if spec.rig_profile else profile.rig_profile]
    item = get_accessory_def(spec.item.ref)
    params = {n: float(spec.params.get(n, d.default)) for n, d in item.params.items()}
    finish = spec.material.finish or item.default_finish
    f = conv.finishes[finish]
    sink: list[Issue] = []
    color = _color(spec.material.color or item.default_color, colors, "", sink) or "#808080"
    accent = None
    if item.accent:
        accent = _color(spec.material.accent_color or item.default_accent or color, colors, "", sink) or color
    point = spec.attach_point or item.attach_points[0]
    return ResolvedAccessory(
        name=spec.name, style_profile=profile.ref, rig_profile=rig.ref, catalog=CATALOG_VERSION, item=item.ref,
        key=item.key, category=item.category, placement=item.placement, attach_point=point,
        attach_bone=rig.attachment_points[point], attach_points=item.attach_points, params=params, finish=finish,
        color=color, accent_color=accent, roughness=f.roughness, specular=f.specular, sheen=f.sheen,
        fit_profiles=tuple(spec.fit_profiles),
        reference_fit_profile=spec.fit_profiles[0] if spec.fit_profiles else DEFAULT_REFERENCE_PROFILE,
        conflicts_with_slots=item.conflicts_with_slots, clearance=conv.thresholds.clearance_m, seed=spec.seed)
