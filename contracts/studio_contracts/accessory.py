"""Accessory specification (SRS 8, architecture 5.3) and its resolution against the
accessory catalog and the finishes of a style profile.

An accessory (``ACC-001``) is its own asset with its own versions: one rigid object that
attaches to a named attachment point of the rig profile (``face_eyes``, ``head_top``,
``wrist_L``, ``hand_R_grip`` …). Several can be put on one character instance in a scene.
Like characters and outfits, the check is pure Python so the API, the AI job and Blender
agree; Blender only ever sees ``ResolvedAccessory``.

Compatibility metadata is what the scene validator checks before anything is loaded: the
rig profile (the attachment point must exist on the character's rig), the body-fit
profiles the accessory is declared for (empty means every profile of the style), and the
attachment points the item may go on.

The catalog is a **procedural stand-in** (``ACCD-*@0.1``) in the same way the garment
catalog is (decision D11, open question Q2): every item is generated by code around the
reference body of a fit profile, not modelled by an artist. Version 0.x on purpose.
"""

from __future__ import annotations

