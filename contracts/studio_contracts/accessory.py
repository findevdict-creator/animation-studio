from studio_contracts.style_profile import HEX, get_style_profile

SCHEMA_VERSION = "accessory_spec/1"
CATALOG_VERSION = "0.1"

Category = Literal["eyewear", "headwear", "wristwear", "bag", "toy"]
#: how an item is cleared from what is under it when it is put on: a ``cover`` (a hat) is
#: scaled about its attachment origin until the head is inside it; a ``ring`` (a watch
#: strap) is scaled about the limb until nothing is inside its band; a ``solid`` (glasses,
#: a bag) is moved along its push direction until it is clear
Placement = Literal["cover", "ring", "solid"]


class _Frozen(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class Model(BaseModel):
    model_config = ConfigDict(extra="forbid")


class ParamDef(_Frozen):
    min: float
    max: float
    default: float
    description: str


class AccessoryDef(_Frozen):
    id: str = Field(pattern=r"^ACCD-[A-Z0-9]+$")
    version: str
    key: str
    label: str
    category: Category
    placement: Placement
    #: rig-profile attachment points the item may go on; the first is the default
    attach_points: tuple[str, ...]
    params: dict[str, ParamDef] = Field(default_factory=dict)
    finishes: tuple[str, ...]
    default_finish: str
    default_color: str
    #: a second colour (lenses, a pompom, a watch face)
    accent: str | None = None
    default_accent: str | None = None
    #: outfit slots whose rigid piece sits on the same attachment point (a beanie and a cap)
    conflicts_with_slots: tuple[str, ...] = ()

    @property
    def ref(self) -> str:
        return f"{self.id}@{self.version}"


def _p(lo: float, hi: float, default: float, text: str) -> ParamDef:
    return ParamDef(min=lo, max=hi, default=default, description=text)


