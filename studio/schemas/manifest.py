"""Library manifest: what the Blender asset library contains.

Generated by tools/scan_library.py. Agents see only this file, never the
.blend files. Every library ID an agent uses must exist here.
"""

from __future__ import annotations

from typing import Literal

from pydantic import Field

from studio.ids import ClipId, LibraryId
from studio.schemas.common import StudioModel

RigType = Literal["rigify_human", "rigify_quadruped", "rigify_bird", "custom"]


class LibraryCharacter(StudioModel):
    id: LibraryId
    file: str
    rig_type: RigType
    height_m: float = Field(gt=0)
    outfit_slots: list[str] = Field(default_factory=list)
    shape_keys: list[str] = Field(default_factory=list)
    tags: list[str] = Field(default_factory=list)


class LibraryProp(StudioModel):
    id: LibraryId
    file: str
    bounds_m: tuple[float, float, float]
    attach_bone: str | None = None
    tags: list[str] = Field(default_factory=list)


class LibraryEnvironment(StudioModel):
    id: LibraryId
    file: str
    bounds_m: tuple[float, float, float]
    anchors: list[str] = Field(default_factory=list)
    time_variants: list[str] = Field(default_factory=list)


class LibraryClip(StudioModel):
    id: ClipId
    rig_type: RigType
    frames: int = Field(gt=0)
    loop: bool = False
    root_motion_m: tuple[float, float, float] = (0.0, 0.0, 0.0)
    tags: list[str] = Field(default_factory=list)
    source: str | None = None
    licence: str | None = None


class LibraryBase(StudioModel):
    """A parametric base mesh with a rig (asset build phase 1)."""

    id: str
    rig_type: RigType
    proportion_sliders: list[str] = Field(default_factory=list)
    material_slots: list[str] = Field(default_factory=list)
    outfit_slots: list[str] = Field(default_factory=list)
    shape_keys: list[str] = Field(default_factory=list)


class LibraryGarment(StudioModel):
    id: str
    slot: str
    fits: list[str] = Field(default_factory=list)
    tags: list[str] = Field(default_factory=list)


class LibraryHair(StudioModel):
    id: str
    fits: list[str] = Field(default_factory=list)


class KitPiece(StudioModel):
    id: str
    footprint_m: tuple[float, float]
    snap_points: list[str] = Field(default_factory=list)
    tags: list[str] = Field(default_factory=list)


class LibraryKit(StudioModel):
    id: str
    pieces: list[KitPiece] = Field(default_factory=list)


class LibraryGenerator(StudioModel):
    id: str
    kind: Literal["terrain", "scatter", "prop"]
    params: dict[str, tuple[float, float]] = Field(default_factory=dict)


class Manifest(StudioModel):
    library_version: str
    units: Literal["metres"] = "metres"
    characters: list[LibraryCharacter] = Field(default_factory=list)
    props: list[LibraryProp] = Field(default_factory=list)
    environments: list[LibraryEnvironment] = Field(default_factory=list)
    clips: list[LibraryClip] = Field(default_factory=list)
    camera_rigs: list[str] = Field(default_factory=lambda: ["static", "dolly", "crane", "handheld_noise"])
    bases: list[LibraryBase] = Field(default_factory=list)
    garments: list[LibraryGarment] = Field(default_factory=list)
    hair: list[LibraryHair] = Field(default_factory=list)
    kits: list[LibraryKit] = Field(default_factory=list)
    generators: list[LibraryGenerator] = Field(default_factory=list)
    lighting_presets: list[str] = Field(default_factory=list)

    # Lookup helpers used by checks and agents.
    def character_by_id(self) -> dict[str, LibraryCharacter]:
        return {c.id: c for c in self.characters}

    def prop_by_id(self) -> dict[str, LibraryProp]:
        return {p.id: p for p in self.props}

    def environment_by_id(self) -> dict[str, LibraryEnvironment]:
        return {e.id: e for e in self.environments}

    def clip_by_id(self) -> dict[str, LibraryClip]:
        return {c.id: c for c in self.clips}

    def base_by_id(self) -> dict[str, LibraryBase]:
        return {b.id: b for b in self.bases}

    def all_library_ids(self) -> set[str]:
        return (
            set(self.character_by_id())
            | set(self.prop_by_id())
            | set(self.environment_by_id())
        )

    @classmethod
    def empty(cls) -> "Manifest":
        return cls(library_version="none")
