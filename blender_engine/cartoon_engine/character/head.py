"""Head: skull, nose and ears (static), eyelids, brows and mouth (driven by a ``FaceState``),
plus the two eyeballs as their own objects.

Every movable part is generated by a function of the face state with a fixed topology, so
the basis mesh and every shape key come from the same code: build the neutral state for the
mesh, then the vertex positions of each state for its shape key.

All objects sit at the world origin with identity transforms; coordinates are world space.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field

from studio_contracts.character import ResolvedCharacter

from cartoon_engine.character.face import NEUTRAL, FaceState, Lids
from cartoon_engine.character.skeleton import Skeleton, Vec, add, mul, norm, sub

#: neutral (upper, lower) lid edge angles in degrees, by eye shape; 0 is the eye's equator
EYE_SHAPES = {"large_rounded": (58.0, -52.0, 1.0), "almond": (34.0, -28.0, 0.9),
              "sleepy": (14.0, -46.0, 0.95), "wide": (72.0, -62.0, 1.05)}
NOSES = {"small": (0.055, 0.045, 0.05), "button": (0.07, 0.06, 0.065), "long": (0.05, 0.11, 0.06),
         "wide": (0.09, 0.05, 0.055)}  # (half width, half depth, half height) as a fraction of head height
MOUTHS = {"friendly": (0.30, 0.25), "small": (0.20, 0.0), "wide": (0.38, 0.1), "neutral": (0.27, 0.0)}  # width, rest smile
EARS = {"default": 1.0, "small": 0.75, "large": 1.3}

HEAD_SLOTS = ("skin", "brow", "mouth", "teeth")  # material index order on the head mesh
LID_ROWS, LID_COLS = 9, 17
BROW_SEGS = 10
MOUTH_U, MOUTH_V = 17, 6


@dataclass
class Layout:
    """Where the face parts sit, worked out once from the skull."""

    center: Vec
    eye_center: dict[str, Vec]
    eye_r: float
    lid_neutral: tuple[float, float]
    brow_half: float
    brow_width: float
    mouth_center: Vec
    mouth_normal: Vec
    mouth_half: float
    mouth_rest_smile: float
    skull_hit: object = field(repr=False, default=None)  # (origin, direction) -> (location, normal)


# ------------------------------------------------------------------- skull
def _skull(sk: Skeleton, rc: ResolvedCharacter):
    import bmesh
    import bpy  # noqa: F401  (import order: bpy before bmesh/mathutils with the wheel)

    bm = bmesh.new()
    bmesh.ops.create_uvsphere(bm, u_segments=48, v_segments=32, radius=1.0)
    cx, cy, cz = sk.head_center
    hw, hd, hh = sk.head_w / 2, sk.head_d / 2, sk.head_h / 2
    square = rc.face_shape == "square"
    cheek = rc.face_sliders.get("cheek_fullness", 0.0)
    chin = rc.face_sliders.get("chin_length", 0.0)
    for v in bm.verts:
        x, y, z = v.co
        if square:  # push towards a rounded cube
            m = max(abs(x), abs(y), abs(z), 1e-6)
            k = 0.22
            x, y, z = x * (1 - k) + x / m * k * 0.82, y * (1 - k) + y / m * k * 0.82, z * (1 - k) + z / m * k * 0.82
        if z < 0:  # jaw: narrower and a little forward towards the chin
            t = (-z) ** 1.3
            x *= 1 - (1 - sk.jaw_narrow) * t
            y -= 0.06 * t * max(0.0, -y)
            z *= 1 + 0.12 * chin
        if z < 0.1 and y < 0.2:  # cheeks
            w = max(0.0, 1 - abs(z + 0.3) / 0.45) * max(0.0, -y + 0.2)
            x *= 1 + 0.08 * (1 + cheek) * w
        v.co = (cx + x * hw, cy + y * hd, cz + z * hh)
    return bm


def _uv_ellipsoid(center: Vec, radii: Vec, segs: int = 16, rings: int = 10) -> tuple[list[Vec], list[tuple]]:
    verts: list[Vec] = []
    faces: list[tuple] = []
    for i in range(1, rings):
        th = math.pi * i / rings
        for j in range(segs):
            ph = 2 * math.pi * j / segs
            verts.append((center[0] + radii[0] * math.sin(th) * math.cos(ph),
                          center[1] + radii[1] * math.sin(th) * math.sin(ph),
                          center[2] + radii[2] * math.cos(th)))
    top, bottom = len(verts), len(verts) + 1
    verts += [(center[0], center[1], center[2] + radii[2]), (center[0], center[1], center[2] - radii[2])]
    for i in range(rings - 2):
        for j in range(segs):
            a, b = i * segs + j, i * segs + (j + 1) % segs
            faces.append((a, b, b + segs, a + segs))
    for j in range(segs):
        faces.append((top, (j + 1) % segs, j))
        last = (rings - 2) * segs
        faces.append((bottom, last + j, last + (j + 1) % segs))
    return verts, faces


def _direction(az_deg: float, el_deg: float) -> Vec:
    az, el = math.radians(az_deg), math.radians(el_deg)
    return (math.sin(az) * math.cos(el), -math.cos(az) * math.cos(el), math.sin(el))


def layout(sk: Skeleton, rc: ResolvedCharacter, skull_bm) -> Layout:
    from mathutils import Vector
    from mathutils.bvhtree import BVHTree

    tree = BVHTree.FromBMesh(skull_bm)
    c = Vector(sk.head_center)

    def hit(direction: Vec) -> tuple[Vec, Vec]:
        loc, normal, _, _ = tree.ray_cast(c, Vector(direction).normalized())
        if loc is None:
            raise RuntimeError(f"face layout: no skull surface towards {direction}")
        n = (loc - c).normalized() * 0.3 + normal.normalized() * 0.7  # tame normals on the jaw seam
        return tuple(loc), tuple(n.normalized())

    upper, lower, size = EYE_SHAPES.get(rc.eye_shape, EYE_SHAPES["large_rounded"])
    eye_r = sk.head_h * (0.085 + 0.06 * rc.eye_size) * size
    spacing = rc.face_sliders.get("eye_spacing", 0.0)
    eyes = {}
    for side, s in (("L", 1.0), ("R", -1.0)):
        loc, n = hit(_direction(s * (21.0 + 5.0 * spacing), -6.0))
        eyes[side] = sub(loc, mul(n, eye_r * 0.42))
    mouth_w, rest_smile = MOUTHS.get(rc.mouth, MOUTHS["friendly"])
    m_loc, m_n = hit(_direction(0.0, -40.0))
    return Layout(center=sk.head_center, eye_center=eyes, eye_r=eye_r, lid_neutral=(upper, lower),
                  brow_half=eye_r * 1.05, brow_width=eye_r * 0.26, mouth_center=m_loc, mouth_normal=m_n,
                  mouth_half=sk.head_w * mouth_w / 2, mouth_rest_smile=rest_smile, skull_hit=hit)


def _project(lay: Layout, p: Vec, offset: float) -> Vec:
    loc, n = lay.skull_hit(sub(p, lay.center))
    return add(loc, mul(n, offset))


# ------------------------------------------------------------- movable parts
def _lid_shell(lay: Layout, side: str, lids: Lids, upper: bool) -> list[Vec]:
    """Half a sphere shell round the eye, rotating about the eye's left-right axis.
    The upper lid covers angles from its edge up over the top to the back; the lower lid
    from its edge down under the eye."""
    c = lay.eye_center[side]
    R = lay.eye_r * 1.07
    up0, low0 = lay.lid_neutral
    if upper:
        edge = max(-85.0, min(85.0, up0 + lids.upper))
        a0, a1 = edge, 200.0
    else:
        edge = max(-85.0, min(60.0, low0 + lids.lower))
        a0, a1 = edge, -200.0
    out = []
    for i in range(LID_ROWS):
        a = math.radians(a0 + (a1 - a0) * i / (LID_ROWS - 1))
        for j in range(LID_COLS):
            b = math.radians(-88.0 + 176.0 * j / (LID_COLS - 1))
            d = (math.sin(b), -math.cos(b) * math.cos(a), math.cos(b) * math.sin(a))
            out.append(add(c, mul(d, R)))
    return out


def _lid_faces(base: int) -> list[tuple]:
    return [(base + i * LID_COLS + j, base + i * LID_COLS + j + 1, base + (i + 1) * LID_COLS + j + 1,
             base + (i + 1) * LID_COLS + j) for i in range(LID_ROWS - 1) for j in range(LID_COLS - 1)]


def _brow(lay: Layout, side: str, state: FaceState) -> list[Vec]:
    brow = state.brow_L if side == "L" else state.brow_R
    s = 1.0 if side == "L" else -1.0
    c = lay.eye_center[side]
    r = lay.eye_r
    out = []
    for k in range(BROW_SEGS):
        t = -1.0 + 2.0 * k / (BROW_SEGS - 1)  # -1 inner end, +1 outer end
        inner_w = (1 - t) / 2
        x = c[0] + s * (t * lay.brow_half - brow.squeeze * r * 0.25 * inner_w)
        z = (c[2] + r * 1.45 + brow.raise_ * r * 0.55 + brow.inner * r * 0.4 * inner_w
             - 0.18 * r * t * t)
        mid = (x, c[1] - r, z)
        width = lay.brow_width * (1.0 - 0.35 * abs(t))
        for dz, off in ((-width / 2, 0.002), (width / 2, 0.002), (width / 2, 0.012), (-width / 2, 0.012)):
            out.append(_project(lay, (mid[0], mid[1], mid[2] + dz), off * lay.eye_r / 0.05))
    return out


def _brow_faces(base: int) -> list[tuple]:
    faces = []
    for k in range(BROW_SEGS - 1):
        a, b = base + k * 4, base + (k + 1) * 4
        for q in range(4):
            faces.append((a + q, a + (q + 1) % 4, b + (q + 1) % 4, b + q))
    faces.append((base + 3, base + 2, base + 1, base + 0))
    e = base + (BROW_SEGS - 1) * 4
    faces.append((e, e + 1, e + 2, e + 3))
    return faces


def _mouth(lay: Layout, state: FaceState) -> list[Vec]:
    m = state.mouth
    half = lay.mouth_half * (1 + 0.3 * m.wide - 0.45 * m.round) * (1 - 0.1 * m.press)
    smile = lay.mouth_rest_smile * (1 - min(1.0, m.open + m.round)) + m.smile
    corner = smile * half * 0.38
    open_ = max(0.0, m.open) * half * 1.3 * (1 + 0.6 * m.round)
    gap = half * 0.035 * (1 - m.press)
    n = lay.mouth_normal
    right: Vec = norm((1.0, 0.0, 0.0))
    up = norm(sub((0.0, 0.0, 1.0), mul(n, n[2])))
    out = []
    for i in range(MOUTH_V):
        f = i / (MOUTH_V - 1)  # 0 upper lip edge .. 1 lower lip edge
        for j in range(MOUTH_U):
            u = -1.0 + 2.0 * j / (MOUTH_U - 1)
            bulge = math.sqrt(max(0.0, 1 - u * u)) if m.round else (1 - u * u)
            prof = bulge ** (1.0 - 0.5 * m.round)
            curve = corner * u * u + m.skew * half * 0.2 * u
            top = curve + (open_ * 0.18 + gap / 2) * prof
            bottom = curve - (open_ * 0.82 + gap / 2) * prof
            v = top + (bottom - top) * f
            x = u * half * (1 - 0.25 * m.round * (1 - prof))
            p = add(lay.mouth_center, add(mul(right, x), mul(up, v)))
            out.append(_project(lay, p, 0.0015 * lay.eye_r / 0.05))
    return out


def _mouth_faces(base: int) -> list[tuple]:
    return [(base + i * MOUTH_U + j, base + (i + 1) * MOUTH_U + j, base + (i + 1) * MOUTH_U + j + 1,
             base + i * MOUTH_U + j + 1) for i in range(MOUTH_V - 1) for j in range(MOUTH_U - 1)]


def movable_vertices(lay: Layout, state: FaceState) -> list[Vec]:
    """Every movable vertex for ``state``, in the order the head mesh stores them."""
    out: list[Vec] = []
    for side in "LR":
        lids = state.lids_L if side == "L" else state.lids_R
        out += _lid_shell(lay, side, lids, upper=True)
        out += _lid_shell(lay, side, lids, upper=False)
    for side in "LR":
        out += _brow(lay, side, state)
    out += _mouth(lay, state)
    return out


# -------------------------------------------------------------------- build
@dataclass
class HeadParts:
    head: object
    eyes: dict[str, object]
    layout: Layout
    static_count: int


def build_head(sk: Skeleton, rc: ResolvedCharacter, materials: dict, name: str = "head") -> HeadParts:
    import bpy

    skull = _skull(sk, rc)
    lay = layout(sk, rc, skull)
    verts: list[Vec] = [tuple(v.co) for v in skull.verts]
    faces: list[tuple] = [tuple(v.index for v in f.verts) for f in skull.faces]
    mats: list[int] = [0] * len(faces)
    skull.free()

    def add_part(vs: list[Vec], fs: list[tuple], material: int) -> None:
        base = len(verts)
        verts.extend(vs)
        for f in fs:
            faces.append(tuple(base + i for i in f))
            mats.append(material)

    hh = sk.head_h
    nose = NOSES.get(rc.nose, NOSES["small"])
    n_loc, n_n = lay.skull_hit(_direction(0.0, -22.0))
    add_part(*_uv_ellipsoid(add(n_loc, mul(n_n, -0.25 * nose[1] * hh)), (nose[0] * hh, nose[1] * hh, nose[2] * hh)), 0)
    ear = EARS.get(rc.ears, 1.0)
    for s in (1.0, -1.0):
        e_loc, _ = lay.skull_hit(_direction(s * 90.0, -8.0))
        add_part(*_uv_ellipsoid(add(e_loc, (s * -0.01 * hh, 0.02 * hh, 0.0)),
                                (0.035 * hh * ear, 0.07 * hh * ear, 0.11 * hh * ear), 12, 8), 0)
    static = len(verts)

    # movable parts, in movable_vertices() order
    lid_n = LID_ROWS * LID_COLS
    neutral = movable_vertices(lay, NEUTRAL)
    base = static
    for _ in range(4):  # upper L, lower L, upper R, lower R
        faces.extend(_lid_faces(base))
        mats.extend([0] * ((LID_ROWS - 1) * (LID_COLS - 1)))
        base += lid_n
    for _ in range(2):
        bf = _brow_faces(base)
        faces.extend(bf)
        mats.extend([1] * len(bf))
        base += BROW_SEGS * 4
    mf = _mouth_faces(base)
    faces.extend(mf)
    # top band of the mouth interior shows teeth once the mouth opens
    mats.extend([3 if i // (MOUTH_U - 1) == 0 else 2 for i in range(len(mf))])
    verts.extend(neutral)

    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    mesh.validate()
    for m in HEAD_SLOTS:
        mesh.materials.append(materials[m])
    for p, mi in zip(mesh.polygons, mats):
        p.material_index = mi
        p.use_smooth = True
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    sub_mod = obj.modifiers.new("subsurf", "SUBSURF")
    sub_mod.levels = 1
    sub_mod.render_levels = 2

    eyes = {side: _eyeball(lay, side, materials) for side in "LR"}
    return HeadParts(head=obj, eyes=eyes, layout=lay, static_count=static)


def _eyeball(lay: Layout, side: str, materials: dict):
    import bpy

    c = lay.eye_center[side]
    r = lay.eye_r
    verts, faces = _uv_ellipsoid((0.0, 0.0, 0.0), (r, r, r), 32, 24)
    # pole along -Y (forward): rotate (x, y, z) -> (x, -z, y)
    verts = [(c[0] + x, c[1] - z, c[2] + y) for x, y, z in verts]
    mesh = bpy.data.meshes.new(f"eye.{side}")
    mesh.from_pydata(verts, [], faces)
    for m in ("eye_white", "iris", "pupil"):
        mesh.materials.append(materials[m])
    fwd = (0.0, -1.0, 0.0)
    for p in mesh.polygons:
        d = norm(sub(tuple(p.center), c))
        ang = math.degrees(math.acos(max(-1.0, min(1.0, sum(a * b for a, b in zip(d, fwd))))))
        p.material_index = 2 if ang < 14 else 1 if ang < 31 else 0
        p.use_smooth = True
    obj = bpy.data.objects.new(f"eye.{side}", mesh)
    bpy.context.scene.collection.objects.link(obj)
    obj["studio_eye_center"] = list(c)
    return obj


def add_shape_keys(parts: HeadParts, states: dict[str, FaceState]) -> list[str]:
    """Basis plus one relative shape key per state; only movable vertices differ."""
    obj = parts.head
    if obj.data.shape_keys is None:
        obj.shape_key_add(name="Basis", from_mix=False)
    names = []
    for key, state in states.items():
        kb = obj.shape_key_add(name=key, from_mix=False)
        kb.slider_min, kb.slider_max = 0.0, 1.0
        kb.value = 0.0  # Blender 5 adds new keys at 1.0
        moved = movable_vertices(parts.layout, state)
        for i, co in enumerate(moved):
            kb.data[parts.static_count + i].co = co
        names.append(key)
    return names
